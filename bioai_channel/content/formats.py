FORMAT_BY_ID: dict[str, PostFormat] = {f.id: f for f in FORMATS}


def get_format(format_id: str) -> PostFormat:
    try:
        return FORMAT_BY_ID[format_id]
    except KeyError as exc:
        raise ValueError(
            f"قالب ناشناخته: {format_id!r}. قالب‌های معتبر: {', '.join(sorted(FORMAT_BY_ID))}"
        ) from exc
